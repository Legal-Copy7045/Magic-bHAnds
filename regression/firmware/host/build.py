"""Build and run the firmware host tests (g++ with ASan/UBSan).

Builds go to regression/out/firmware-host/. Used by ../host_tests.py; can be
run alone:  python3 build.py test_put_dimmed.cpp [extra.cpp ...]
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
BUILD = REPO / "regression" / "out" / "firmware-host"
VENV = Path(os.environ.get("ESPHOME_VENV", "/tmp/claude-0/esphvenv"))
CXX = os.environ.get("CXX", shutil.which("g++") or "g++")
SANITIZE = ["-fsanitize=address,undefined,float-cast-overflow", "-fno-sanitize-recover=all"]


def site_packages() -> Path | None:
    for p in sorted((VENV / "lib").glob("python3*/site-packages")):
        if (p / "esphome").is_dir():
            return p
    try:
        import esphome  # noqa: F401
        return Path(esphome.__file__).resolve().parents[1]
    except ImportError:
        return None


def prepare() -> Path:
    """Gamma table from ESPHome's own generator, and the component under esphome/components/."""
    inc = BUILD / "inc"
    (inc / "esphome" / "components").mkdir(parents=True, exist_ok=True)
    link = inc / "esphome" / "components" / "magicband"
    if link.is_symlink() or link.exists():
        link.unlink()
    link.symlink_to(REPO / "components" / "magicband")
    py = VENV / "bin" / "python"
    code = ("from esphome.components.light import generate_gamma_table as g;"
            "print(','.join(str(int(v)) for v in g(2.8)))")
    vals = subprocess.run([str(py if py.exists() else sys.executable), "-c", code], capture_output=True, text=True, check=True).stdout.strip()
    (inc / "gamma_table.h").write_text(
        "#pragma once\n// ESPHome's gamma table for gamma 2.8 (light.generate_gamma_table), generated by build.py.\n"
        "#include <cstdint>\nstatic const uint16_t GAMMA_2_8[256] = {" + vals + "};\n")
    return inc


def compile_test(sources: list[Path], name: str, defines: list[str] = (), sanitize: bool = True) -> tuple[Path | None, str]:
    inc = prepare()
    sp = site_packages()
    exe = BUILD / name
    cmd = [CXX, "-std=gnu++20", "-O1", "-g", "-Wall", "-Wno-unused-variable", "-Wno-unused-but-set-variable",
           "-Wno-unused-function", *(SANITIZE if sanitize else []), f"-I{HERE / 'mock'}", f"-I{inc}", f"-I{HERE}"]
    if sp:
        cmd.append(f"-I{sp}")
    cmd += [f"-D{d}" for d in defines] + [str(s) for s in sources] + ["-o", str(exe), "-lm"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        return None, " ".join(cmd) + "\n" + r.stderr[-6000:]
    return exe, r.stderr[-3000:]


def run_test(exe: Path, args: list[str] = (), stdin: str | None = None, timeout: int = 600) -> tuple[int, str, str]:
    env = dict(os.environ, ASAN_OPTIONS="detect_leaks=0:abort_on_error=0", UBSAN_OPTIONS="print_stacktrace=1:halt_on_error=1")
    r = subprocess.run([str(exe), *args], capture_output=True, text=True, input=stdin, timeout=timeout, env=env)
    return r.returncode, r.stdout, r.stderr


if __name__ == "__main__":
    srcs = [HERE / a for a in sys.argv[1:]]
    exe, log = compile_test(srcs, Path(sys.argv[1]).stem)
    print(log)
    if exe:
        rc, out, err = run_test(exe)
        print(out, err[-3000:], "rc", rc)
